package ru.mirea.delivery.http;

/**
 * Доступ к маршруту. Закрытость — по умолчанию (SEC-2): у каждого
 * маршрута доступ записан явно в таблице маршрутов контроллера.
 */
public enum Access {
    /** Без входа: служебные проверки и показатели. */
    PUBLIC,
    /** Служебный токен соседа ({@code order}), без пользователя. */
    INTERNAL,
    /** Токен пользователя и одна из ролей маршрута. */
    USER
}
